  <h1>Privacy notice</h1>
  <p class="muted">Draft — to be reviewed before launch.</p>

  <h2>What we store</h2>
  <ul>
    <li><b>Account:</b> your display name (public), email address (never shown to other players), and a
      one-way hash of your password (we can't read your password).</li>
    <li><b>Sessions:</b> a login cookie, valid for 30 days or until you log out. We store only a hash of it.</li>
    <li><b>Games:</b> every match you play and every hand dealt in it, including <b>all hole cards —
      both players', even folded or mucked hands</b>. Other players never see cards you didn't show;
      this full record is kept so we can check matches for collusion and chip-dumping before awarding
      prizes.</li>
    <li><b>Ratings:</b> your rating and the results of your matches, shown on the public leaderboard
      under your display name.</li>
  </ul>

  <h2>Why</h2>
  <p>To run the ladder, keep games fair, decide prize winners, and contact winners. We don't sell
    your data or use it for advertising. Email is used for account confirmation and prize matters only.</p>

  <h2>Free to enter</h2>
  <p>No payment is needed to play or to win a prize. Prizes are funded by sponsors.</p>
