<article class="doc">
  <h1>Privacy notice</h1>
  <p class="note small">This is a draft and will be reviewed before seasons with prizes begin.</p>

  <h2>What we store</h2>
  <ul>
    <li>
      <b>Your account:</b> your display name (public), your email address (never shown to other
      players), and a one-way hash of your password. We can't read your password.
    </li>
    <li>
      <b>Sessions:</b> a login cookie, valid for 30 days or until you log out. We store only a hash
      of it.
    </li>
    <li>
      <b>Games:</b> every match you play and every hand dealt in it, including <b>all hole cards,
      both players', even in hands that were folded or mucked</b>. Other players never see cards you
      didn't show. We keep the full record so matches can be checked for collusion and chip dumping
      before prizes are awarded.
    </li>
    <li>
      <b>Ratings:</b> your rating and your match results, shown on the public leaderboard under your
      display name.
    </li>
  </ul>

  <h2>Why</h2>
  <p>
    To run the ladder, keep games fair, decide prize winners, and contact them. We don't sell your
    data or use it for advertising. We only email you to confirm your account, to reset your password
    when you ask, to tell you if someone tries to sign up with your address, and about prizes.
  </p>

  <h2>Free to enter</h2>
  <p>No payment is needed to play or to win a prize. Prizes are paid for by sponsors.</p>
</article>

